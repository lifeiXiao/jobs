import {chromium} from 'playwright';
import fs from 'node:fs/promises';
if(process.env.GITHUB_ACTIONS!=='true'||process.env.RUNNER_ENVIRONMENT!=='github-hosted')throw Error('Run measurements on GitHub-hosted runners');
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:390,height:844},isMobile:true,deviceScaleFactor:1});
const session=await page.context().newCDPSession(page);
await session.send('Network.enable');
await session.send('Network.emulateNetworkConditions',{offline:false,latency:150,downloadThroughput:200000,uploadThroughput:90000});
await session.send('Emulation.setCPUThrottlingRate',{rate:4});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('https://xjob.pages.dev/',{waitUntil:'domcontentloaded',timeout:90000});
await page.locator('.job-card').first().waitFor({timeout:90000});
const result=await page.evaluate(()=>({listReadyMs:Math.round(performance.now()),resources:performance.getEntriesByType('resource').map(r=>({name:new URL(r.name).pathname,host:new URL(r.name).hostname,transfer:r.transferSize,decoded:r.decodedBodySize,durationMs:Math.round(r.duration)})),records:document.querySelector('#stat-total').textContent}));
await page.locator('[data-preview]').first().click();
await page.locator('#detail-dialog').waitFor({state:'visible'});
await page.getByRole('heading',{name:'岗位与招聘要求 · 简要摘录'}).waitFor({timeout:30000});
result.errors=errors;result.label=process.env.MEASURE_LABEL;
await fs.mkdir('performance',{recursive:true});
await fs.writeFile('performance/result.json',JSON.stringify(result,null,2));
await page.screenshot({path:'performance/mobile-detail.png'});
console.log(JSON.stringify(result));
await browser.close();
