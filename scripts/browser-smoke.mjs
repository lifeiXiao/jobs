import{chromium}from'playwright';
import assert from'node:assert/strict';
import fs from'node:fs/promises';
const browser=await chromium.launch({headless:true,channel:'chrome'});
const page=await browser.newPage({viewport:{width:1440,height:1100}});
const errors=[];page.on('pageerror',e=>errors.push(e.message));
await page.goto('https://lifeixiao.github.io/jobs/',{waitUntil:'networkidle'});
await page.locator('.job-card').first().waitFor();
const count=Number((await page.locator('#result-count').textContent()).replaceAll(',',''));
assert.ok(count>0,'Live site must have real recruiting records');
await page.locator('[data-preview]').first().click();
await page.locator('#detail-dialog').waitFor({state:'visible'});
assert.ok((await page.locator('#detail-body').textContent()).includes('投递截止'));
assert.ok((await page.locator('#detail-body').textContent()).includes('岗位与招聘要求'));
assert.ok(!(await page.locator('#detail-body').textContent()).includes('var arg1'));
assert.ok((await page.url()).includes('lifeixiao.github.io/jobs/'),'Preview must stay on site');
await page.locator('#close-detail').click();
const cityChoices=page.locator('#city-options input');
await cityChoices.nth(0).check();
assert.equal(await page.locator('#city-options input:checked').count(),1);
await page.locator('[data-mode="city"][data-value="single"]').click();
await cityChoices.nth(1).check();
assert.equal(await page.locator('#city-options input:checked').count(),1);
await page.locator('[data-mode="city"][data-value="multi"]').click();
await cityChoices.nth(0).check();
assert.equal(await page.locator('#city-options input:checked').count(),2);
await page.locator('#reset').click();
await page.locator('#keyword').fill('____no_such_job____');
assert.equal(await page.locator('.job-card').count(),0);
await page.locator('#reset').click();
assert.ok(Number((await page.locator('#result-count').textContent()).replaceAll(',',''))>=count);
assert.equal(await page.locator('#keyword').inputValue(),'');
await page.locator('#only-dated').check();
await page.locator('#sort').selectOption('deadline');
if(await page.locator('.job-card').count())assert.ok((await page.locator('.deadline').first().textContent()).includes('截止'));
await page.locator('#reset').click();
await page.locator('#source-button').click();
await page.locator('#sources-dialog').waitFor({state:'visible'});
assert.ok(await page.locator('.source-row').count()>=4);
await page.locator('#close-sources').click();
await fs.mkdir('screenshots',{recursive:true});
await page.screenshot({path:'screenshots/desktop.png'});
await page.setViewportSize({width:390,height:844});
await page.screenshot({path:'screenshots/mobile.png'});
assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=innerWidth),'Mobile must not overflow');
await page.locator('[data-preview]').first().click();
await page.locator('#detail-dialog').waitFor({state:'visible'});
await page.screenshot({path:'screenshots/mobile-detail.png'});
assert.deepEqual(errors,[],'No browser exceptions');
console.log(JSON.stringify({liveRecords:count,desktop:true,mobile:true,filters:true,preview:true,errors}));
await browser.close();
